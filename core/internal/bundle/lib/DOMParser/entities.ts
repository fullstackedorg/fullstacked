// The references the browser also expands without the semicolon (legacy
// HTML, "&copy 2026", "&amp" in a URL): the Latin-1 names, whose values are
// U+00A0 to U+00FF (&COPY; and &REG; among them), and amp, lt, gt and quot
// in both cases. Their names are 6 characters at most.
export const LEGACY_ENTITIES: Set<string> = new Set(
    Object.keys(HTML_ENTITIES).filter((name) => {
        const value = HTML_ENTITIES[name];
        const code = value.charCodeAt(0);
        return (
            (value.length === 1 && code >= 0xa0 && code <= 0xff) ||
            /^(amp|lt|gt|quot)$/i.test(name)
        );
    })
);
